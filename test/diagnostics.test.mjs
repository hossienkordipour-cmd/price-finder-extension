import assert from 'node:assert/strict';
import {createDiagnostics,DIAGNOSTICS_KEY,MAX_EVENTS,MAX_AGE_MS,safeEvent,createSearchTrace} from '../diagnostics.js';
import {diagnosticFetch} from '../request-diagnostics.js';
const uuid=()=>crypto.randomUUID();
const searchId=uuid();
let time=Date.now(),rows={};
const storage={async get(key){return structuredClone({[key]:rows[key]});},async set(value){Object.assign(rows,structuredClone(value));}};
let received=[],fail=true;
const fetcher=async(_,options)=>{
 if(fail)throw new Error('offline');
 const events=JSON.parse(options.body).events;received.push(...events);
 return {ok:true,json:async()=>({accepted_ids:events.map(e=>e.event_id)})};
};
const config={storage,endpoint:'http://127.0.0.1/events',version:'1.1.0',fetcher,now:()=>time};
let d=createDiagnostics(config);
await d.emit({event_name:'search_started',search_id:searchId,url:'https://private/?q=secret',query:'secret',name:'private product',error:'secret',duration_ms:NaN});
const event=rows[DIAGNOSTICS_KEY][0].event;
assert.equal(event.duration_ms,null);
for(const key of ['url','query','name','error'])assert.equal(key in event,false);
await d.flush();assert.equal(rows[DIAGNOSTICS_KEY][0].attempts,1);
d=createDiagnostics(config); // Worker restart uses persisted queue/backoff.
fail=false;await d.flush();assert.equal(received.length,0);
time+=31000;await d.flush();assert.equal(rows[DIAGNOSTICS_KEY].length,0);assert.equal(received.length,1);
await Promise.all(Array.from({length:MAX_EVENTS+15},()=>d.emit({event_name:'search_started',search_id:uuid()})));
assert.equal(rows[DIAGNOSTICS_KEY].length,MAX_EVENTS);
time+=MAX_AGE_MS+1;await d.flush();assert.equal(rows[DIAGNOSTICS_KEY].length,0);
let resolveFetch;config.fetcher=()=>new Promise(resolve=>{resolveFetch=resolve;});d=createDiagnostics(config);
await d.emit({event_name:'search_started',search_id:searchId});
const flushing=d.flush();await new Promise(r=>setImmediate(r));
await d.emit({event_name:'search_finished',search_id:searchId,status:'completed'});
const first=rows[DIAGNOSTICS_KEY][0].event.event_id;
resolveFetch({ok:true,json:async()=>({accepted_ids:[first]})});await flushing;
assert.equal(rows[DIAGNOSTICS_KEY].length,1,'Acknowledgement cannot overwrite events appended in flight');
assert.equal(rows[DIAGNOSTICS_KEY][0].event.event_name,'search_finished');
const trace=createSearchTrace(null,uuid(),()=>time);
const fetchJSON=diagnosticFetch(async()=>new Response(JSON.stringify({results:[]})),trace);
await (await fetchJSON('https://api.torob.com/search')).json();
assert.equal(trace.requests.at(-1).status,'empty');
await assert.rejects(async()=>await (await diagnosticFetch(async()=>new Response('{}'),trace)('https://api.torob.com/search')).json());
assert.equal(trace.requests.at(-1).status,'parse_error');
await diagnosticFetch(async()=>new Response('',{status:503}),trace)('https://api.torob.com/search');
assert.equal(trace.requests.at(-1).status,'http_error');
await assert.rejects(diagnosticFetch(async()=>{throw new DOMException('timeout','AbortError');},trace)('https://api.torob.com/search'));
assert.equal(trace.requests.at(-1).status,'timeout');
await assert.rejects(diagnosticFetch(async()=>{throw new TypeError('network secret');},trace)('https://api.torob.com/search'));
assert.equal(trace.requests.at(-1).status,'network_error');
assert.equal(trace.finish(0),'partial_failure');
assert.equal(new Set(trace.requests.map(r=>r.source_request_id)).size,5);
const shared=createSearchTrace(null);shared.link(trace);assert.equal(shared.networkId,trace.id);
assert.equal(shared.events.filter(e=>e.event_name==='request_finished').length,0);
assert.equal(safeEvent({event_name:'not_allowed'},'1.1.0'),null);
console.log('Diagnostics: privacy allowlist, persisted retries/restart, expiry/cap, concurrent flush, source errors and shared identity passed');
