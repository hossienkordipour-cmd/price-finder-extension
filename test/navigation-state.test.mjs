import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
import * as stateTools from '../tab-state.js';
const source=await readFile(new URL('../background.js',import.meta.url),'utf8');
const old={name:'کیسه فریزر',source:'etkala',sourceUrl:'https://etkala.ir/products/1/',price:157500};
const next={name:'مرغ',source:'etkala',sourceUrl:'https://etkala.ir/products/2/',price:873000};
const storage={'tabState:1':{currentProduct:old,productKey:'etkala|'+old.sourceUrl+'|'+old.name,requestId:42,searchResults:[old]}};
const events=[],pending=[],listeners={};
const registry=process.argv.includes('--without-fix')?class extends stateTools.TabSearchRegistry {begin(id){return super.begin(id,0)}}:stateTools.TabSearchRegistry;
const ctx=vm.createContext({console,Date,URL,setTimeout,clearTimeout,AbortController,...stateTools,TabSearchRegistry:registry,normalizeProductText:v=>v,SearchResultCache:class{},chrome:{
  runtime:{onInstalled:{addListener(){}},onMessage:{addListener(fn){listeners.message=fn}},sendMessage(m){events.push(m);return Promise.resolve()}},action:{onClicked:{addListener(){}},setPopup(){}},
  tabs:{onRemoved:{addListener(){}},onUpdated:{addListener(fn){listeners.updated=fn}},onActivated:{addListener(){}}},storage:{local:{async get(keys){return Object.fromEntries(keys.map(k=>[k,storage[k]]))},async set(v){Object.assign(storage,v)}}}}});
vm.runInContext(source.replace(/import\s+[\s\S]*?\s+from\s+['"][^'"]+['"];?/g,''),ctx);
ctx.old=old;ctx.next=next;ctx.pending=pending;
vm.runInContext('searchPrices=(product,options)=>new Promise(resolve=>pending.push({product,options,resolve}))',ctx);
await vm.runInContext('registerDetectedProduct(1,next)',ctx);
assert.equal(storage['tabState:1'].currentProduct.name,'مرغ','Restart must not retain request 42 product');
assert.ok(storage['tabState:1'].requestId>42);
await vm.runInContext('startTabSearch(1,next)',ctx);
assert.equal(pending.length,1);
const searchVersion=storage['tabState:1'].requestId;
await vm.runInContext("invalidateTabPage(1,'https://etkala.ir/search/category',true)",ctx);
assert.equal(storage['tabState:1'].currentProduct,null);
assert.equal(storage['tabState:1'].searchResults,null);
assert.ok(storage['tabState:1'].requestId>searchVersion);
const before=events.length;
pending[0].options.onProgress([next]);pending[0].resolve([next]);
await new Promise(resolve=>setImmediate(resolve));
assert.equal(events.length,before,'Old progress/final must not be broadcast');
assert.equal(storage['tabState:1'].currentProduct,null);
await vm.runInContext('startTabSearch(1,next)',ctx);
assert.equal(pending.length,1,'Old sidebar may not restart product from another page');
await vm.runInContext('registerDetectedProduct(1,next)',ctx);
assert.equal(storage['tabState:1'].currentProduct,null,'Delayed old-page detection ignored');
await vm.runInContext("invalidateTabPage(1,'https://etkala.ir/products/1/',true)",ctx);
await vm.runInContext('registerDetectedProduct(1,old)',ctx);
assert.equal(storage['tabState:1'].currentProduct.name,'کیسه فریزر');
assert.equal(events.at(-1).type,'PRODUCT_UPDATED');
const beforeDelayedPage=events.length;
listeners.message({type:'PAGE_CHANGED',url:next.sourceUrl},{tab:{id:1,url:old.sourceUrl}},()=>{});
await new Promise(resolve=>setImmediate(resolve));
assert.equal(events.length,beforeDelayedPage,'Delayed old content may not invalidate current page');
console.log('Restart counter, navigation reset, late results and stale start/detection tests passed');
